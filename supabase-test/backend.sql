-- Test application only. The migration snapshot in sibil_stage stays immutable.
begin;
create schema sibil_test;
revoke all on schema sibil_test from public,anon,authenticated;
create table sibil_test.customers (
 id uuid primary key default gen_random_uuid(),
 sort_no bigint generated by default as identity unique,
 source_id uuid unique references sibil_stage.customers(id) on delete restrict,
 name text not null check(length(btrim(name)) between 1 and 150),
 created_at timestamptz not null default now()
);
create table sibil_test.statuses (
 customer_id uuid not null references sibil_test.customers(id) on delete restrict,
 year integer not null check(year=2026),
 month integer not null check(month between 1 and 12),
 status text not null check(status in ('CASH','TRANSFER','DISCOUNT','UNPAID')),
 version integer not null default 0 check(version>=0),
 primary key(customer_id,year,month)
);
create table sibil_test.requests (
 actor uuid not null, request_id uuid not null, action text not null,
 body jsonb not null, response jsonb not null, created_at timestamptz not null default now(),
 primary key(actor,request_id)
);
create table sibil_test.audit (
 id bigint generated always as identity primary key,
 actor uuid not null, request_id uuid not null, action text not null,
 customer_id uuid not null references sibil_test.customers(id) on delete restrict,
 before_value jsonb, after_value jsonb not null, at timestamptz not null default now(),
 foreign key(actor,request_id) references sibil_test.requests(actor,request_id) deferrable initially deferred
);
create index sibil_test_audit_customer on sibil_test.audit(customer_id);
create index sibil_test_audit_request on sibil_test.audit(actor,request_id);
create table sibil_test.revoked_sessions(session_id uuid primary key, revoked_at timestamptz not null default now());
alter table sibil_test.customers enable row level security;
alter table sibil_test.statuses enable row level security;
alter table sibil_test.requests enable row level security;
alter table sibil_test.audit enable row level security;
alter table sibil_test.revoked_sessions enable row level security;
insert into sibil_test.customers(source_id,name)
select id,name from sibil_stage.customers order by source_row;
insert into sibil_test.statuses(customer_id,year,month,status)
select c.id,2026,s.month,s.status from sibil_stage.payment_statuses s
join sibil_test.customers c on c.source_id=s.customer_id;

create function public.sibil_test_api(p_actor uuid,p_session uuid,p_email text,p_action text,p_body jsonb default '{}')
returns jsonb language plpgsql security invoker set search_path='' as $fn$
declare rid uuid; cached sibil_test.requests%rowtype; cid uuid; old sibil_test.statuses%rowtype;
 result jsonb; requested text; nm text; m integer; desired_version integer;
begin
 if p_actor is null or p_session is null or p_email is distinct from 'ekoprabowojob@gmail.com' then
  raise exception using errcode='42501',message='Admin verification required'; end if;
 if exists(select 1 from sibil_test.revoked_sessions where session_id=p_session) then
  raise exception using errcode='42501',message='Session revoked'; end if;
 if p_action='logout' then
  insert into sibil_test.revoked_sessions(session_id) values(p_session) on conflict do nothing;
  return jsonb_build_object('message','Logged out');
 end if;
 if p_action='dashboard' then
  return jsonb_build_object('customers',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'source_row',sort_no,'name',name) order by sort_no),'[]') from sibil_test.customers),
   'statuses',(select coalesce(jsonb_agg(jsonb_build_object('customer_id',s.customer_id,'source_row',c.sort_no,'month',s.month,'status',s.status,'version',s.version) order by c.sort_no,s.month),'[]') from sibil_test.statuses s join sibil_test.customers c on c.id=s.customer_id where s.year=2026));
 end if;
 if p_action not in ('update','addCustomer') then raise exception using errcode='22023',message='Unknown action'; end if;
 rid:=(p_body->>'request_id')::uuid;
 if rid is null then raise exception using errcode='22023',message='Request ID required'; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_actor::text||rid::text,0));
 select * into cached from sibil_test.requests where actor=p_actor and request_id=rid;
 if found then
  if cached.action<>p_action or cached.body<>p_body then raise exception using errcode='40001',message='Request ID reused with different input'; end if;
  return cached.response;
 end if;
 if p_action='update' then
  cid:=(p_body->>'customer_id')::uuid; m:=(p_body->>'month')::integer;
  requested:=p_body->>'status'; desired_version:=(p_body->>'version')::integer;
  if requested is null or requested not in ('CASH','TRANSFER','DISCOUNT','UNPAID') or m is null or m not between 1 and 12 or desired_version is null then raise exception using errcode='22023',message='Invalid payment input'; end if;
  select * into old from sibil_test.statuses where customer_id=cid and year=2026 and month=m for update;
  if not found then raise exception using errcode='22023',message='Customer/month not found'; end if;
  if old.version<>desired_version then raise exception using errcode='40001',message='Data changed; reload before saving'; end if;
  update sibil_test.statuses set status=requested,version=version+1 where customer_id=cid and year=2026 and month=m;
  result:=jsonb_build_object('message','Status salinan uji berhasil disimpan.','version',old.version+1);
  insert into sibil_test.audit(actor,request_id,action,customer_id,before_value,after_value)
   values(p_actor,rid,p_action,cid,to_jsonb(old),jsonb_build_object('year',2026,'month',m,'status',requested,'version',old.version+1));
 else
  nm:=btrim(p_body->>'name');
  if nm is null or length(nm) not between 1 and 150 or nm ~ '^[=+@-]' or nm ~ '[\r\n\t]' then raise exception using errcode='22023',message='Invalid customer name'; end if;
  perform pg_catalog.pg_advisory_xact_lock(718412679);
  if exists(select 1 from sibil_test.customers where lower(name)=lower(nm)) then raise exception using errcode='23505',message='Customer already exists'; end if;
  insert into sibil_test.customers(name) values(nm) returning id into cid;
  insert into sibil_test.statuses(customer_id,year,month,status) select cid,2026,g,'UNPAID' from generate_series(1,12) g;
  result:=jsonb_build_object('message','Pelanggan salinan uji berhasil ditambahkan.','id',cid);
  insert into sibil_test.audit(actor,request_id,action,customer_id,after_value) values(p_actor,rid,p_action,cid,jsonb_build_object('name',nm));
 end if;
 insert into sibil_test.requests(actor,request_id,action,body,response) values(p_actor,rid,p_action,p_body,result);
 return result;
end $fn$;
revoke all on function public.sibil_test_api(uuid,uuid,text,text,jsonb) from public,anon,authenticated;
grant execute on function public.sibil_test_api(uuid,uuid,text,text,jsonb) to service_role;
grant usage on schema sibil_test to service_role;
revoke all on all tables in schema sibil_test from public,anon,authenticated;
grant select,insert on sibil_test.customers,sibil_test.requests,sibil_test.audit,sibil_test.revoked_sessions to service_role;
grant select,insert,update on sibil_test.statuses to service_role;
grant usage,select on all sequences in schema sibil_test to service_role;
commit;

